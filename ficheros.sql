

/* 1. Consulta de empleados y departamentos */

SELECT
    e.employee_id,
    e.first_name,
    e.last_name,
    d.department_name
FROM employees e
INNER JOIN departments d
    ON e.department_id = d.department_id;


/* 2. Generación del documento XML */

SELECT
    XMLSERIALIZE(
        DOCUMENT
        XMLELEMENT("empleados",
            XMLAGG(
                XMLELEMENT("empleado",
                    XMLATTRIBUTES(e.employee_id AS "id"),
                    XMLFOREST(
                        e.first_name AS "nombre",
                        e.last_name AS "apellido",
                        d.department_name AS "departamento"
                    )
                )
            )
        )
        AS CLOB INDENT SIZE = 2
    ) AS documento_xml
FROM employees e
INNER JOIN departments d
    ON e.department_id = d.department_id;


/* 3. Registro del esquema XML */

BEGIN
    DBMS_XMLSCHEMA.REGISTERSCHEMA(
        SCHEMAURL => 'empleados.xsd',
        SCHEMADOC => XMLTYPE(
            BFILENAME('XML_DIR', 'empleados.xsd'),
            NLS_CHARSET_ID('AL32UTF8')
        )
    );
END;
/


/* 4. Creación de la tabla */

CREATE TABLE empleados_xml_tab (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento XMLTYPE
);


/* 5. Inserción de XML válido */

INSERT INTO empleados_xml_tab (documento)
VALUES (
    XMLTYPE(
        BFILENAME('XML_DIR', 'empleados.xml'),
        NLS_CHARSET_ID('AL32UTF8')
    ).createSchemaBasedXML('empleados.xsd')
);

COMMIT;


/* 6. Inserción de XML no válido */

INSERT INTO empleados_xml_tab (documento)
VALUES (
    XMLTYPE(
        '<empleados>
            <empleado id="999">
                <nombre>Prueba</nombre>
                <apellido>Incorrecto</apellido>
            </empleado>
        </empleados>'
    ).createSchemaBasedXML('empleados.xsd')
);

COMMIT;


/* 7. Validación de los documentos XML */

SELECT
    id,
    XMLISVALID(documento, 'empleados.xsd') AS XML_VALIDO
FROM empleados_xml_tab;


/* 8. Validación del XML no válido */

SELECT XMLISVALID(
    XMLTYPE(
        '<empleados>
            <empleado id="999">
                <nombre>Prueba</nombre>
                <apellido>Incorrecto</apellido>
            </empleado>
        </empleados>'
    ).createSchemaBasedXML('empleados.xsd'),
    'empleados.xsd'
) AS RESULTADO
FROM DUAL;



    
